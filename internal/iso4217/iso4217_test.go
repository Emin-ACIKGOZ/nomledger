const (
	listOneFile       = "list-one.xml"
	listOneSHA256     = "33139b438657d1cee116ba737807ea71d19d6de4b90f799a09c56f0cc6a1b0ff"
	listOneSize       = 47491
	listOnePublished  = "2026-09-17"
	listOneSourceURL  = "https://www.six-group.com/dam/download/financial-information/data-center/iso-currrency/lists/list-one.xml"
	listTwoFile       = "list-two.txt"
	listTwoSourceURL  = "https://www.six-group.com/dam/download/financial-information/data-center/iso-currrency/lists/list-two.doc"
	listTwoSHA256     = "2c59a66ec930fd72332b7aebb6f5d940205497ca4ab39c6d34a076af2d70468c"
	listTwoRetrieved  = "2026-11-04"
	listTwoFundLine   = "XAD BOV CLF COU MXV CHW CHE USN UYI UYW"
	expectedCodeCount = 178
	expectedXMLRows   = 280
	expectedEmptyRows = 3
	generatedPrefix   = "// SPDX-License-Identifier: MIT\n// Code generated by internal/iso4217/gen; DO NOT EDIT.\n"
)

// documentedFunds is a second, independent copy of the SIX List Two fund set.
// The primary expectation comes from parsing list-two.txt; this map guards
// against accidental edits to that file.
var documentedFunds = map[string]bool{
	"XAD": true,
	"BOV": true,
	"CLF": true,
	"COU": true,
	"MXV": true,
	"CHW": true,
	"CHE": true,
	"USN": true,
	"UYI": true,
	"UYW": true,
}

type listOneXML struct {
	XMLName   xml.Name     `xml:"ISO_4217"`
	Published string       `xml:"Pblshd,attr"`
	Rows      []listOneRow `xml:"CcyTbl>CcyNtry"`
}

type listOneRow struct {
	Country    string `xml:"CtryNm"`
	Name       string `xml:"CcyNm"`
	Code       string `xml:"Ccy"`
	Numeric    string `xml:"CcyNbr"`
	MinorUnits string `xml:"CcyMnrUnts"`
}

func readListOne(t *testing.T) []byte {
	t.Helper()
	data, err := os.ReadFile(listOneFile)
	if err != nil {
		t.Fatalf("read %s: %v", listOneFile, err)
	}
	return data
}

func parseListOne(t *testing.T) listOneXML {
	t.Helper()
	var doc listOneXML
	if err := xml.Unmarshal(readListOne(t), &doc); err != nil {
		t.Fatalf("parse %s: %v", listOneFile, err)
	}
	return doc
}

// readListTwo parses the derived List Two fund-code file independently of the
// generator and asserts that its provenance block matches the recorded source.
func readListTwo(t *testing.T) []string {
	t.Helper()
	data, err := os.ReadFile(listTwoFile)
	if err != nil {
		t.Fatalf("read %s: %v", listTwoFile, err)
	}

	for _, want := range []string{listTwoSourceURL, listTwoSHA256, listTwoRetrieved} {
		if !strings.Contains(string(data), want) {
			t.Errorf("%s provenance is missing %q", listTwoFile, want)
		}
	}

	var codes []string
	dataLines := 0
	for i, line := range strings.Split(string(data), "\n") {
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		dataLines++
		if dataLines > 1 {
			t.Fatalf("%s line %d: more than one fund-code line", listTwoFile, i+1)
		}
		codes = append(codes, strings.Fields(line)...)
	}
	if dataLines != 1 {
		t.Fatalf("%s has %d fund-code lines; want 1", listTwoFile, dataLines)
	}
	if got := strings.Join(codes, " "); got != listTwoFundLine {
		t.Errorf("%s fund line = %q; want %q", listTwoFile, got, listTwoFundLine)
	}
	return codes
}

func fundSet(t *testing.T) map[string]bool {
	t.Helper()
	set := make(map[string]bool)
	for _, code := range readListTwo(t) {
		set[code] = true
	}
	if len(set) != len(documentedFunds) {
		t.Errorf("parsed fund set has %d codes; want %d", len(set), len(documentedFunds))
	}
	for code := range documentedFunds {
		if !set[code] {
			t.Errorf("parsed fund set is missing %s", code)
		}
	}
	for code := range set {
		if !documentedFunds[code] {
			t.Errorf("parsed fund set contains unexpected code %s", code)
		}
	}
	return set
}

// expectedEntries independently derives the expected registry from the XML.
// Duplicate Ccy rows are collapsed; "No universal currency" rows without a
// Ccy are skipped. An "N.A." minor-unit value is represented as MinorUnits 0
// with Ratable false.
func expectedEntries(t *testing.T) map[string]iso4217.Entry {
	t.Helper()
	doc := parseListOne(t)
	funds := fundSet(t)
	if doc.Published != listOnePublished {
		t.Errorf("XML Pblshd = %q; want %q", doc.Published, listOnePublished)
	}

	got := make(map[string]iso4217.Entry, expectedCodeCount)
	emptyRows := 0
	for i, row := range doc.Rows {
		if row.Code == "" {
			emptyRows++
			continue
		}

		minor, ratable, err := expectedMinorUnits(row.MinorUnits)
		if err != nil {
			t.Fatalf("row %d (%s, %s): %v", i, row.Country, row.Code, err)
		}
		want := iso4217.Entry{
			Code:       row.Code,
			Numeric:    row.Numeric,
			Name:       row.Name,
			MinorUnits: minor,
			Ratable:    ratable,
			Fund:       funds[row.Code],
		}

		if prev, ok := got[row.Code]; ok {
			if prev != want {
				t.Fatalf("inconsistent duplicate XML rows for %s: %+v != %+v", row.Code, prev, want)
			}
			continue
		}
		got[row.Code] = want
	}

	if len(doc.Rows) != expectedXMLRows {
		t.Errorf("XML rows = %d; want %d", len(doc.Rows), expectedXMLRows)
	}
	if emptyRows != expectedEmptyRows {
		t.Errorf("XML rows with empty Ccy = %d; want %d", emptyRows, expectedEmptyRows)
	}
	if len(got) != expectedCodeCount {
		t.Fatalf("XML unique codes = %d; want %d", len(got), expectedCodeCount)
	}
	return got
}

func expectedMinorUnits(raw string) (int32, bool, error) {
	if raw == "N.A." {
		return 0, false, nil
	}
	switch raw {
	case "0", "2", "3", "4":
		n, err := strconv.ParseInt(raw, 10, 32)
		if err != nil {
			return 0, false, err
		}
		return int32(n), true, nil
	default:
		return 0, false, &unexpectedMinorUnitsError{raw: raw}
	}
}

type unexpectedMinorUnitsError struct{ raw string }

func (e *unexpectedMinorUnitsError) Error() string {
	return "unexpected CcyMnrUnts value " + strconv.Quote(e.raw)
}

// TestListOneHash: the checked-in source must match its recorded
// provenance (SHA-256 and byte size).
func TestListOneHash(t *testing.T) {
	data := readListOne(t)

	if len(data) != listOneSize {
		t.Errorf("size of %s = %d bytes; want %d", listOneFile, len(data), listOneSize)
	}

	sum := sha256.Sum256(data)
	if got := hex.EncodeToString(sum[:]); got != listOneSHA256 {
		t.Errorf("SHA-256 of %s = %s; want %s", listOneFile, got, listOneSHA256)
	}
}

// TestListTwoProvenance: the List Two fund-code source.
func TestListTwoProvenance(t *testing.T) {
	codes := readListTwo(t)
	if len(codes) != len(documentedFunds) {
		t.Errorf("List Two codes = %d; want %d", len(codes), len(documentedFunds))
	}
	for _, code := range codes {
		if !documentedFunds[code] {
			t.Errorf("List Two contains unexpected fund code %s", code)
		}
	}
}

// TestEntriesMatchXML: set and field equality between the
// generated table and the checked-in SIX List One source.
func TestEntriesMatchXML(t *testing.T) {
	wantByCode := expectedEntries(t)

	entries := iso4217.Entries()
	if len(entries) != expectedCodeCount {
		t.Fatalf("Entries() returned %d codes; want %d", len(entries), expectedCodeCount)
	}

	assertMinorDistribution(t, entries)

	for code, want := range wantByCode {
		t.Run(code, func(t *testing.T) {
			assertEntryMatches(t, entries, code, want)
		})
	}
	assertNoExtraCodes(t, entries, wantByCode)
}

// assertMinorDistribution checks the documented minor-unit counts over
// ratable codes and the non-ratable code count.
func assertMinorDistribution(t *testing.T, entries []iso4217.Entry) {
	t.Helper()
	minorCounts := map[int32]int{}
	nonRatable := 0
	seen := make(map[string]bool, len(entries))
	for _, e := range entries {
		if seen[e.Code] {
			t.Errorf("Entries() contains duplicate code %s", e.Code)
		}
		seen[e.Code] = true
		if e.Ratable {
			minorCounts[e.MinorUnits]++
		} else {
			nonRatable++
		}
	}

	wantMinor := map[int32]int{0: 17, 2: 139, 3: 7, 4: 2}
	for precision, want := range wantMinor {
		if got := minorCounts[precision]; got != want {
			t.Errorf("ratable codes with %d minor units = %d; want %d", precision, got, want)
		}
	}
	if len(minorCounts) != len(wantMinor) {
		t.Errorf("ratable minor-unit values = %v; want exactly %v", minorCounts, wantMinor)
	}
	if nonRatable != 13 {
		t.Errorf("non-ratable codes = %d; want 13", nonRatable)
	}
}

func assertEntryMatches(t *testing.T, entries []iso4217.Entry, code string, want iso4217.Entry) {
	t.Helper()
	got, ok := findEntry(entries, code)
	if !ok {
		t.Fatalf("Entries() is missing code %s from XML", code)
	}
	if got.Code != want.Code {
		t.Errorf("Code = %q; want %q", got.Code, want.Code)
	}
	if got.Numeric != want.Numeric {
		t.Errorf("Numeric = %q; want %q", got.Numeric, want.Numeric)
	}
	if got.Name != want.Name {
		t.Errorf("Name = %q; want %q", got.Name, want.Name)
	}
	if got.MinorUnits != want.MinorUnits {
		t.Errorf("MinorUnits = %d; want %d", got.MinorUnits, want.MinorUnits)
	}
	if got.Ratable != want.Ratable {
		t.Errorf("Ratable = %t; want %t", got.Ratable, want.Ratable)
	}
	if got.Fund != want.Fund {
		t.Errorf("Fund = %t; want %t (List Two)", got.Fund, want.Fund)
	}
}

func assertNoExtraCodes(t *testing.T, entries []iso4217.Entry, wantByCode map[string]iso4217.Entry) {
	t.Helper()
	for _, got := range entries {
		if _, ok := wantByCode[got.Code]; !ok {
			t.Errorf("Entries() contains %s which is absent from the XML", got.Code)
		}
	}
}

func findEntry(entries []iso4217.Entry, code string) (iso4217.Entry, bool) {
	for _, e := range entries {
		if e.Code == code {
			return e, true
		}
	}
	return iso4217.Entry{}, false
}

func TestEntriesSortedAndUnique(t *testing.T) {
	entries := iso4217.Entries()

	seen := make(map[string]bool, len(entries))
	var codes []string
	for _, e := range entries {
		if seen[e.Code] {
			t.Errorf("duplicate code %s", e.Code)
		}
		seen[e.Code] = true
		codes = append(codes, e.Code)
	}

	if !sort.StringsAreSorted(codes) {
		t.Errorf("Entries() is not sorted by Code: %v", codes)
	}
}

func TestEntriesReturnsCopy(t *testing.T) {
	first := iso4217.Entries()
	if len(first) == 0 {
		t.Fatal("Entries() returned an empty table")
	}

	original := first[0]
	first[0].Code = "ZZZ"
	first[0].Numeric = "000"
	first[0].Name = "mutated"
	first[0].MinorUnits = 99
	first[0].Ratable = !original.Ratable
	first[0].Fund = !original.Fund
	appended := append(iso4217.Entries(), iso4217.Entry{Code: "QQQ"})
	if len(appended) != expectedCodeCount+1 {
		t.Errorf("appended slice length = %d; want %d", len(appended), expectedCodeCount+1)
	}

	second := iso4217.Entries()
	if second[0] != original {
		t.Errorf("mutating returned slice changed the registry: got %+v; want %+v", second[0], original)
	}
	if _, ok := findEntry(second, "ZZZ"); ok {
		t.Error("mutating returned slice injected code ZZZ into the registry")
	}
	if _, ok := findEntry(second, "QQQ"); ok {
		t.Error("appending to returned slice injected code QQQ into the registry")
	}
}

// TestGeneratorDeterministic: running the generator against the
// checked-in sources must reproduce table_gen.go byte-for-byte and record its
// provenance in the header. The -funds flag is left at its list-two.txt
// default, resolved relative to this package directory.
func TestGeneratorDeterministic(t *testing.T) {
	outPath := filepath.Join(t.TempDir(), "table_gen.go")
	cmd := exec.CommandContext(context.Background(), "go", "run", "./gen", "-xml", listOneFile, "-out", outPath) //nolint:gosec // fixed local generator invocation, no user input
	cmd.Dir = "."
	if out, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("go run ./gen failed: %v\n%s", err, out)
	}

	generated, err := os.ReadFile(outPath) //nolint:gosec // test-local temp file
	if err != nil {
		t.Fatalf("read generated file: %v", err)
	}
	checkedIn, err := os.ReadFile("table_gen.go")
	if err != nil {
		t.Fatalf("read table_gen.go: %v", err)
	}
	if !bytes.Equal(generated, checkedIn) {
		t.Error("regenerated table differs from checked-in table_gen.go; run go generate ./...")
	}

	for name, content := range map[string][]byte{
		"regenerated": generated,
		"checked-in":  checkedIn,
	} {
		text := string(content)
		if !strings.HasPrefix(text, generatedPrefix) {
			t.Errorf("%s does not start with the SPDX/generated marker %q", name, generatedPrefix)
		}
		for _, want := range []string{
			listOneSourceURL,
			listOnePublished,
			listOneSHA256,
			listTwoSourceURL,
			listTwoSHA256,
			listTwoRetrieved,
			"Fund codes: " + listTwoFundLine,
			"go generate ./...",
		} {
			if !strings.Contains(text, want) {
				t.Errorf("%s header does not contain %q", name, want)
			}
		}
		if strings.Contains(text, "lists/list-two.xml") {
			t.Errorf("%s still references the stale List Two XML URL", name)
		}
	}
}

func TestFundFlags(t *testing.T) {
	entries := iso4217.Entries()
	funds := fundSet(t)
	if len(funds) != len(documentedFunds) {
		t.Fatalf("parsed fund set has %d codes; want %d", len(funds), len(documentedFunds))
	}

	assertFundCount(t, entries, funds)
	assertDocumentedFundsFlagged(t, entries)
	assertNonFundsNotFlagged(t, entries)
}

func assertFundCount(t *testing.T, entries []iso4217.Entry, funds map[string]bool) {
	t.Helper()
	fundCount := 0
	for _, e := range entries {
		if e.Fund {
			fundCount++
		}
		if want := funds[e.Code]; e.Fund != want {
			t.Errorf("%s Fund = %t; want %t (List Two)", e.Code, e.Fund, want)
		}
	}
	if fundCount != len(documentedFunds) {
		t.Errorf("entries flagged Fund = %d; want %d", fundCount, len(documentedFunds))
	}
}

func assertDocumentedFundsFlagged(t *testing.T, entries []iso4217.Entry) {
	t.Helper()
	for code := range documentedFunds {
		e, ok := findEntry(entries, code)
		if !ok {
			t.Errorf("List Two fund code %s is absent from Entries()", code)
			continue
		}
		if !e.Fund {
			t.Errorf("List Two fund %s is not flagged Fund", code)
		}
	}
}

func assertNonFundsNotFlagged(t *testing.T, entries []iso4217.Entry) {
	t.Helper()
	for _, code := range []string{"USD", "XAU", "XTS", "XXX"} {
		e, ok := findEntry(entries, code)
		if !ok {
			t.Errorf("representative non-fund code %s is absent from Entries()", code)
			continue
		}
		if e.Fund {
			t.Errorf("representative non-fund %s is flagged Fund", code)
		}
	}
}
